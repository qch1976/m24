import {reduceFix,cntRecip,numLeaf,recipLeaf} from './lib-input06-recip.mjs';
const R=t=>t.op==='num'?String(t.card):t.op==='recip'?`(1/${t.arg.card})`:`(${R(t.a)}${t.op}${R(t.b)})`;
const L=numLeaf,Rc=recipLeaf,B=(op,a,b)=>({op,a,b});
// §1.2.3 归约的已知盲区候选：加减链内数值抵消 / 0 参与
const T=[
 ['12/(((1/2)+3)-3)', B('/',L(12),B('-',B('+',Rc(2),L(3)),L(3)))],
 ['4/(((1/6)+7)-7)',  B('/',L(4),B('-',B('+',Rc(6),L(7)),L(7)))],
 ['(2*3)/((1/4)-0)',  B('/',B('*',L(2),L(3)),B('-',Rc(4),L(0)))],
 ['(2*3)/((1/4)+0)',  B('/',B('*',L(2),L(3)),B('+',Rc(4),L(0)))],
 ['3/(((1/8)-1)+1)',  B('/',L(3),B('+',B('-',Rc(8),L(1)),L(1)))],
 ['(3*6)/(1-(1/4))',  B('/',B('*',L(3),L(6)),B('-',L(1),Rc(4)))],
];
console.log('§1.2.3 归约盲区扫描（加减链内可数值抵消 / 0 项）');
for(const [lab,t] of T){const rr=reduceFix(t);
 console.log(`${lab.padEnd(20)}→ 归约 ${R(rr.node).padEnd(30)} 判定=${cntRecip(rr.node)>0?'有效':'无效'}`);}
console.log(`
说明：前 5 例归约后仍含 1/x（判"有效"），但其数学等价的非倒数式存在：
  12/(((1/2)+3)-3) = 12/(1/2) = 12*2      （加减链内 +3-3 抵消）
  4/(((1/6)+7)-7)  = 4/(1/6)  = 4*6
  (2*3)/((1/4)-0)  = (2*3)/(1/4) = 2*3*4  （减 0 恒等）
  3/(((1/8)-1)+1)  = 3/(1/8)   = 3*8
§1.2.3 的归约规则只做「乘除链翻面消去」，不做加减链的数值化简与 ±0 归零，
故此类解会被判为"有效倒数解"。这是规范的字面结果，也是 §8 基准数字的口径。`);
